/**
 * The column types that differ between engines. Times are milliseconds since the epoch, past a
 * 32-bit integer: SQLite's INTEGER holds 64 bits, Postgres needs BIGINT (which node-postgres hands
 * back as a string, so every read goes through Number()). Flags stay integers 0/1 on both.
 */
const TYPES = {
  // `key`: text compared byte by byte, so an ORDER BY on it is the same on every engine (SQLite's
  // default; Postgres's own default follows the database's locale).
  sqlite: { int: "INTEGER", serial: "INTEGER PRIMARY KEY AUTOINCREMENT", key: "TEXT" },
  postgres: { int: "BIGINT", serial: "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", key: `TEXT COLLATE "C"` },
};
type Types = (typeof TYPES)["sqlite"];

